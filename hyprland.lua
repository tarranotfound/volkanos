-- Volkanos Hyprland configuration

local terminal = "kitty"
local menu = "fuzzel"
local mainMod = "SUPER"

-- Monitor
hl.monitor({
    output = "",
    mode = "preferred",
    position = "auto",
    scale = "auto",
})

-- Autostart
hl.exec_cmd("kitty --single-instance --override initial_window_width=640 --override initial_window_height=360")

-- Environment
hl.env("XCURSOR_SIZE", "24")
hl.env("HYPRCURSOR_SIZE", "24")

-- General / layout / decoration
hl.config({
    general = {
        gaps_in = 4,
        gaps_out = 8,
        border_size = 3,
        col = {
            active_border = {
                colors = { "rgba(ef101fff)" },
